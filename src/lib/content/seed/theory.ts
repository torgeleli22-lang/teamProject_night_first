import { getConcept } from "../../curriculum";
import type { Level, Skill } from "../../types";
import type { SeedQuestion, SeedSet } from "./types";

/**
 * 개념 학습 시드: 주제 하나 = 객관식 문제 묶음 (코드 없음).
 * 보기는 화면에 섞어서 보여 주므로(문제 id 로 정해진 순서) 작성할 때는 정답을 맨 앞에 둔다.
 * 오답 보기에는 그 보기를 고르는 사람의 오개념을 적어, AI 없이 오답 원인을 보여 준다.
 */

type Wrong = [text: string, misconception?: string];

function mc(
  id: string,
  skill: Skill,
  prompt: string,
  correct: string,
  wrongs: Wrong[],
  hints: string[],
  explanation: string,
  keyPoint: string,
  certs?: string[],
): SeedQuestion {
  return {
    id,
    type: "multiple_choice",
    skill,
    prompt,
    choices: [{ text: correct }, ...wrongs.map(([text, misconception]) => (misconception ? { text, misconception } : { text }))],
    answerIndex: 0,
    hints,
    explanation,
    keyPoint,
    ...(certs ? { certs } : {}),
  };
}

/** 주제 묶음. certs 는 문제마다 따로 정하지 않았으면 이 값을 쓴다 */
function topic(concept: string, level: Level, certs: string[], questions: SeedQuestion[]): SeedSet {
  return {
    id: `th-${concept}`,
    track: "theory",
    title: getConcept(concept)?.name ?? concept,
    code: "",
    concepts: [concept],
    output: null,
    runnable: false,
    level,
    questions: questions.map((q) => ({ ...q, certs: q.certs ?? certs })),
  };
}

