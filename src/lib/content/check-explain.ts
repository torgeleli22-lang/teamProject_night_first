/** [ai-xxx-q3] → "3번 문제" */
function questionLabel(name: string): string | null {
  const m = /^\[[^\]]*-q(\d+)\]/.exec(name);
  return m ? `${m[1]}번 문제` : null;
}

export function explainCheck(name: string): string | null {
  const hit = EXPLAIN.find(([re]) => re.test(name));
  if (!hit) return null;
  const q = questionLabel(name);
  return q ? `${q}: ${hit[1]}` : hit[1];
}
